import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const failures=[];
const checksCount=14;
const check=(name,ok)=>{console.log((ok?'PASS':'FAIL')+': '+name);if(!ok)failures.push(name)};
const main=read('src/main.jsx');
const campus=read('src/v14-platform-plus.jsx');
const extras=read('src/extra-features.jsx');
const css=read('src/styles/public-system.css')+'\n'+read('src/jyc-logo-final-theme.css');
const browser=read('scripts/browser-smoke.spec.js');
const cssImports=main.match(/import ['"][^'"]+\.css['"];?/g)||[];
check('public entry stylesheet is mounted exactly once without duplicate CSS imports',cssImports.length===1&&cssImports[0].includes('styles/public-entry.css')&&new Set(cssImports).size===cssImports.length);
check('visible focus indicator is defined',/:focus-visible/.test(css)&&/outline:\s*(?:2|3)px/.test(css));
check('touch targets meet the project 44px contract',/min-width:\s*44px/.test(css)&&/min-height:\s*44px/.test(css));
check('reduced motion is explicitly supported',/prefers-reduced-motion:\s*reduce/.test(css));
check('forced-colors support is present',/forced-colors:\s*active/.test(css));
check('homepage browser QA checks missing image alt',browser.includes("img:not([alt])"));
check('homepage browser QA checks unnamed buttons',browser.includes('unnamedButtons'));
check('homepage browser QA checks horizontal overflow',browser.includes('scrollWidth'));
check('no positive tabindex values are introduced',!/tabIndex\s*=\s*\{\s*[1-9]\d*\s*\}|tabindex\s*=\s*["'][1-9]\d*["']/i.test(main));
check('skip link exists',main.includes('SkipLink')&&/className=["']skip-link["']/.test(extras)&&!read('index.html').includes('class="skip-link"'));
check('filter controls expose pressed state',/aria-pressed=\{family===/.test(main)&&/aria-pressed=\{!savedOnly\}/.test(extras)&&/aria-pressed=\{savedOnly\}/.test(extras));
const publicButtonFiles=['src/main.jsx','src/extra-features.jsx','src/jyc-editorial-home.jsx','src/jyc-next-experience.jsx','src/jyc-now.jsx','src/featured-event-popup.jsx','src/jyc-bot.jsx','src/jyc-history-page.jsx','src/jyc57-experience.jsx','src/jyc-spotlight.jsx'];
check('public buttons declare an explicit type',publicButtonFiles.every(file=>{const text=read(file);return [...text.matchAll(/<button\b([^>]*)>/g)].every(m=>/\btype\s*=/.test(m[1]));}));
check('filter groups do not misuse tablist semantics without tabs',!/className="hub-family-row" role="tablist"/.test(main)&&!/className="calendar-mode-tabs" role="tablist"/.test(extras));
check('campus selector is a button group with pressed state',campus.includes('className="campus-switch" role="group"')&&campus.includes('aria-pressed={campus===x.id}'));
if(failures.length) process.exit(1);
console.log('Accessibility contract QA PASS ('+(checksCount-failures.length)+' checks)');